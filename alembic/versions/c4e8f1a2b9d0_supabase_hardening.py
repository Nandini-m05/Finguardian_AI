def _statements(sql: str) -> list[str]:
    """Split a script into single statements, keeping $$-quoted bodies whole.

    asyncpg (used by SQLAlchemy here) prepares every statement, and a
    prepared statement cannot contain several commands - so the script is
    sent one statement at a time. Only $$ quoting is tracked, which is
    all these scripts use for bodies that contain semicolons.
    """
    statements, buf, in_dollar, i = [], [], False, 0
    while i < len(sql):
        if sql.startswith("$$", i):
            in_dollar = not in_dollar
            buf.append("$$")
            i += 2
            continue
        ch = sql[i]
        if ch == ";" and not in_dollar:
            stmt = "".join(buf).strip()
            if stmt and not all(line.strip().startswith("--") or not line.strip() for line in stmt.splitlines()):
                statements.append(stmt)
            buf = []
        else:
            buf.append(ch)
        i += 1
    tail = "".join(buf).strip()
    if tail and not all(line.strip().startswith("--") or not line.strip() for line in tail.splitlines()):
        statements.append(tail)
    return statements


